import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

/* data/hostels.json is derived from the flyers repo's seed/hostels.json, the
   one place hostel names come from (only Artur supplies them). Run
   `npm run sync:hostels` after a hostel is added there; `-- --check` only
   compares and fails when the copy is stale. Point FLYERS_SEED at the file
   if the flyers repo is not checked out next to this one. */

const ROOT = join(import.meta.dirname, '..');
const OUT = join(ROOT, 'data', 'hostels.json');
const FLYERS_SEED =
  process.env.FLYERS_SEED ?? join(ROOT, '..', 'nest-flyers', 'nest-branded-flyers-generator', 'seed', 'hostels.json');

type FlyersHostel = { slug: string; name: string; island: string; sort_order?: number };

/* Island ids are the geometry file names; the flyers repo uses display names. */
const islandIdByName = new Map(
  readdirSync(join(ROOT, 'data', 'geometry')).map((file) => {
    const geo = JSON.parse(readFileSync(join(ROOT, 'data', 'geometry', file), 'utf8')) as { name: string };
    return [geo.name, basename(file, '.geo.json')] as const;
  }),
);

if (!existsSync(FLYERS_SEED)) {
  console.error(`Flyers seed not found at ${FLYERS_SEED} (set FLYERS_SEED).`);
  process.exit(1);
}

const flyers = JSON.parse(readFileSync(FLYERS_SEED, 'utf8')) as { hostels: FlyersHostel[] };
const hostels = [...flyers.hostels]
  .sort((a, b) => (a.sort_order ?? 0) - (b.sort_order ?? 0))
  .map((h) => {
    const island = islandIdByName.get(h.island);
    if (!island) throw new Error(`${h.slug}: no geometry for island "${h.island}"`);
    return { slug: h.slug, name: h.name, island };
  });

const content =
  JSON.stringify(
    {
      _note:
        'Generated by `npm run sync:hostels` from nest-branded-flyers-generator/seed/hostels.json. Do not edit: hostel names come only from there.',
      hostels,
    },
    null,
    2,
  ) + '\n';

const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
if (process.argv.includes('--check')) {
  if (current !== content) {
    console.error('data/hostels.json is stale: run `npm run sync:hostels`.');
    process.exit(1);
  }
  console.log(`data/hostels.json matches the flyers seed (${hostels.length} hostels).`);
} else if (current === content) {
  console.log(`data/hostels.json is up to date (${hostels.length} hostels).`);
} else {
  writeFileSync(OUT, content);
  console.log(`wrote data/hostels.json (${hostels.length} hostels).`);
}
